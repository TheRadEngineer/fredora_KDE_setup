#!/usr/bin/env bash
# =============================================================================
# setup-aliases.sh — Host aliases (Fedora, Docker-based ROS containers)
# Lives at: fedora_KDE_setup/5-SETUP-ALIASES/setup-aliases.sh
#
# Installs ~/.bashrc.d/host-aliases.sh (Fedora's native mechanism). It only
# loads on the HOST; inside a container it does nothing.
#
# The `1` / `2` shell commands for the ROS containers are real programs
# (/usr/local/bin/1, /usr/local/bin/2, created by each env's install.sh), so
# this script deliberately does NOT define aliases with those names.
#
# USAGE:
#   ./setup-aliases.sh              install / update
#   ./setup-aliases.sh --remove     remove the aliases file
#   ./setup-aliases.sh --show       print what would be installed
#
# To change things: edit ROS_ENVS or generate_aliases() below, then re-run.
# =============================================================================

set -uo pipefail

ALIASES_DIR="$HOME/.bashrc.d"
ALIASES_FILE="$ALIASES_DIR/host-aliases.sh"

if [[ -t 1 ]]; then
    BOLD=$'\e[1m'; NORMAL=$'\e[0m'
    GREEN=$'\e[32m'; YELLOW=$'\e[33m'; BLUE=$'\e[34m'; CYAN=$'\e[36m'
else
    BOLD=""; NORMAL=""; GREEN=""; YELLOW=""; BLUE=""; CYAN=""
fi
info() { echo -e "${BLUE}${BOLD}[INFO]${NORMAL}  $*"; }
ok()   { echo -e "${GREEN}${BOLD}[ OK ]${NORMAL}  $*"; }
warn() { echo -e "${YELLOW}${BOLD}[WARN]${NORMAL}  $*"; }

# =============================================================================
# ROS ENVIRONMENTS — systemd service name : shell command : workspace folder
# (service = folder in /opt/ros-containers; add one line per environment)
# =============================================================================
ROS_ENVS=(
    "ros1:1:anscer_ws"
    "ros2:2:ros2_ws"
)

generate_aliases() {
cat <<'HEADER'
# =============================================================================
# Host Aliases — generated by setup-aliases.sh (re-run it to update;
# manual edits here will be overwritten).
# Host only: skipped inside Docker containers.
# =============================================================================

[[ -n "${CONTAINER_NAME:-}" || -f /.dockerenv ]] && return 0

# =============================================================================
# ROS containers (systemd services). Shell inside them: the `1` / `2` commands.
# =============================================================================
HEADER

local entry svc num ws
for entry in "${ROS_ENVS[@]}"; do
    IFS=':' read -r svc num ws <<< "$entry"
    cat <<ROSBLOCK
alias ${svc}-start='sudo systemctl start ${svc}'
alias ${svc}-stop='sudo systemctl stop ${svc}'
alias ${svc}-restart='sudo systemctl restart ${svc}'
alias ${svc}-save='sudo systemctl reload ${svc}'
alias ${svc}-status='systemctl status ${svc}'
alias ${svc}-log='journalctl -u ${svc} -b'
alias ws${num}='cd ~/${ws}'
ROSBLOCK
done

cat <<'SECTION'

# =============================================================================
# System
# =============================================================================

# update: DNF + Flatpak (user & system) + firmware check + NVIDIA/CDI + reboot check
update() {
    echo "==> DNF packages"
    sudo dnf upgrade --refresh -y || { echo "DNF failed — stopping."; return 1; }

    if command -v flatpak &>/dev/null; then
        echo; echo "==> Flatpak (user)"
        flatpak update --user -y
        echo "==> Flatpak (system)"
        sudo flatpak update --system -y
        flatpak uninstall --unused -y >/dev/null 2>&1
    fi

    if command -v fwupdmgr &>/dev/null; then
        echo; echo "==> Firmware (check only)"
        fwupdmgr refresh --force >/dev/null 2>&1
        if fwupdmgr get-updates >/dev/null 2>&1; then
            echo "Firmware updates available. Apply with: fwupdmgr update"
        else
            echo "No firmware updates."
        fi
    fi

    if command -v nvidia-ctk &>/dev/null && [[ -d /etc/cdi ]]; then
        echo; echo "==> NVIDIA container (CDI) spec"
        if nvidia-smi &>/dev/null; then
            sudo nvidia-ctk cdi generate --output=/etc/cdi/nvidia.yaml >/dev/null 2>&1 \
                && echo "CDI spec refreshed." || echo "CDI refresh failed — run: cdi-refresh"
        else
            echo "NVIDIA driver not loaded (just updated?). Reboot, then run: cdi-refresh"
        fi
    fi

    echo
    if sudo dnf needs-restarting -r >/dev/null 2>&1; then
        echo "Done. No reboot needed."
    else
        echo "Done. REBOOT recommended (kernel or core libraries updated)."
    fi
}
alias installed='dnf list --installed'
alias search='dnf search'
alias cleanup='sudo dnf autoremove -y && sudo dnf clean all'
alias reboot='sudo systemctl reboot'
alias poweroff='sudo systemctl poweroff'
alias services='systemctl list-units --type=service --state=running'
alias journal='journalctl -xe'
alias diskspace='df -h --type=btrfs --type=ext4'
alias bigfiles='du -sh ~/* | sort -rh | head -20'

# =============================================================================
# NVIDIA / ASUS
# =============================================================================
alias gpu='nvidia-smi'
alias gpuwatch='watch -n 1 nvidia-smi'
# Run after every NVIDIA driver update (containers need a fresh CDI spec)
alias cdi-refresh='sudo nvidia-ctk cdi generate --output=/etc/cdi/nvidia.yaml && nvidia-ctk cdi list'

if command -v asusctl &>/dev/null; then
    alias performance='asusctl profile -P Performance'
    alias balanced='asusctl profile -P Balanced'
    alias quiet='asusctl profile -P Quiet'
    alias profile='asusctl profile -p'
fi

if command -v supergfxctl &>/dev/null; then
    alias gpumode='supergfxctl -g'
    alias hybrid='sudo supergfxctl -m Hybrid'
    alias dgpu='sudo supergfxctl -m Dedicated'
    alias igpu='sudo supergfxctl -m Integrated'
fi

# =============================================================================
# Docker
# =============================================================================
alias d='docker'
alias dc='docker compose'
alias dps='docker ps --format "table {{.Names}}\t{{.Status}}\t{{.Ports}}"'
alias dpsa='docker ps -a --format "table {{.Names}}\t{{.Status}}\t{{.Ports}}"'
alias dimages='docker images --format "table {{.Repository}}\t{{.Tag}}\t{{.Size}}"'
alias dlogs='docker logs -f'
alias dexec='docker exec -it'
alias ddf='docker system df'
# Asks first. Removes stopped containers, unused networks, dangling images and
# build cache (not images used by a running container).
alias dprune='read -r -p "Run docker system prune? [y/N] " ans && [[ "$ans" =~ ^[Yy]$ ]] && docker system prune -f || echo "Cancelled"'

# =============================================================================
# Git  (gcl = clone with the right GitHub account, see ssh-manager.sh)
# =============================================================================
alias g='git'
alias gs='git status'
alias ga='git add'
alias gaa='git add -A'
alias gc='git commit -m'
alias gca='git commit --amend'
alias gp='git push'
alias gpf='git push --force-with-lease'
alias gl='git pull'
alias gf='git fetch --all --prune'
alias glog='git log --oneline --graph --decorate -20'
alias gloga='git log --oneline --graph --decorate --all -30'
alias gd='git diff'
alias gds='git diff --staged'
alias gb='git branch'
alias gba='git branch -a'
alias gco='git checkout'
alias gsw='git switch'
alias gsc='git switch -c'
alias gcl='git profile clone'
alias gst='git stash'
alias gstp='git stash pop'
alias gcp='git cherry-pick'
alias grb='git rebase'
alias grbi='git rebase -i'
alias gm='git merge'

# =============================================================================
# Navigation
# =============================================================================
alias ..='cd ..'
alias ...='cd ../..'
alias ....='cd ../../..'
alias ll='ls -alFh'
alias la='ls -A'
alias lt='ls -ltrh'
alias mkd='mkdir -pv'
alias proj='cd ~/Projects'

# =============================================================================
# Editors (only if installed)
# =============================================================================
if command -v zed &>/dev/null; then alias z='zed .'; fi

# =============================================================================
# Misc
# =============================================================================
alias ports='ss -tulnp'
alias myip='curl -s ifconfig.me && echo'
alias weather='curl wttr.in/?format=3'
alias path='echo $PATH | tr ":" "\n"'
alias reload='source ~/.bashrc && echo "Reloaded"'
SECTION
}

case "${1:-}" in
    --remove)
        if [[ -f "$ALIASES_FILE" ]]; then
            rm "$ALIASES_FILE"; ok "Removed $ALIASES_FILE"
            info "Run 'source ~/.bashrc' or open a new terminal"
        else warn "Nothing to remove"; fi
        ;;
    --show)
        generate_aliases
        ;;
    *)
        mkdir -p "$ALIASES_DIR"
        [[ -f "$ALIASES_FILE" ]] && warn "Existing aliases file found — will be overwritten"
        generate_aliases > "$ALIASES_FILE"
        chmod 644 "$ALIASES_FILE"
        ok "Aliases installed to $ALIASES_FILE"

        if grep -q 'bashrc\.d' "$HOME/.bashrc" 2>/dev/null; then
            ok "~/.bashrc already sources ~/.bashrc.d/"
        else
            warn "~/.bashrc doesn't source ~/.bashrc.d/ — add this to it:"
            echo '    if [ -d ~/.bashrc.d ]; then'
            echo '        for rc in ~/.bashrc.d/*; do [ -f "$rc" ] && . "$rc"; done'
            echo '    fi'
        fi

        echo
        info "Run 'source ~/.bashrc' or open a new terminal to activate."
        echo
        echo -e "${BOLD}ROS containers:${NORMAL}"
        for entry in "${ROS_ENVS[@]}"; do
            IFS=':' read -r svc num ws <<< "$entry"
            echo -e "  ${CYAN}${num}${NORMAL}  shell in ${svc} (a real command, not an alias)"
            echo -e "     ${svc}-start | -stop | -restart | -save | -status | -log      ws${num} = cd ~/${ws}"
        done
        echo
        echo -e "${BOLD}Also:${NORMAL} gcl <link> clones with the right GitHub account; cdi-refresh after NVIDIA driver updates."
        ;;
esac
